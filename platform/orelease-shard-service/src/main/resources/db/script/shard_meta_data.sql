CREATE OR REPLACE FUNCTION GET_VIRTUAL_SHARD(
    ENTITY_ID UUID
)
RETURNS INT
LANGUAGE SQL
AS
$$
SELECT MOD(
    (
        'X' ||
        SUBSTRING(
            REPLACE(ENTITY_ID::TEXT,'-','')
            FROM 1 FOR 8
        )
    )::BIT(32)::BIGINT,
    1024
)::INT;
$$;